def _load_reprobe_cli_module():
    root = Path(__file__).resolve().parents[1]
    script = root / "scripts/q3d_reprobe_geometry.py"
    spec = importlib.util.spec_from_file_location("q3d_reprobe_geometry_test", script)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_canonical_probe_contract_is_fixed_and_accepts_explicit_schedule():
    module = _load_reprobe_cli_module()
    schedule = [
        [1, 1, 1],
        [1, 2, 2],
        [1, 2, 2],
        [2, 2, 2],
        [1, 2, 2],
        [1, 2, 2],
    ]
    params = module.canonical_probe_parameters(schedule)
    assert params["samples"] == 16
    assert params["seed_start"] == 42
    assert params["seed_end_inclusive"] == 57
    assert params["shape_zyx"] == [33, 97, 97]
    assert params["stage_index"] == 3
    assert params["channel_aggregation"] == "signed_mean_all_stage_channels"
    assert params["padding_mode"] == "replicate"
    assert params["decision_threshold_voxels"] == 2.0
    assert params["stride_schedule_zyx"] == schedule
    with pytest.raises(ValueError):
        module.canonical_probe_parameters([[1, 1, 1]] * 5)
    with pytest.raises(ValueError):
        module.canonical_probe_parameters([[1.5, 1, 1]] * 6)


