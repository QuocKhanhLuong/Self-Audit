    assert anisotropy["definition"] == (
        "median across TRAIN patients of max(spacing_zyx_mm) / min(spacing_zyx_mm); "
        "each ratio is computed before taking the median"
    )
    assert summary["planner_inputs"]["patch_size_zyx_voxels_unchanged"] == [8.5, 127.5, 127.5]
    assert summary["planner_inputs"]["resampling"] == "none"
    assert summary["planner_inputs"]["target_spacing"] == "none"
    assert summary["planner_inputs"]["planner_conv_kernels_applied_to_teacher"] is False
    assert summary["planner_output"]["teacher_kernel_sizes_preserved_zyx"] == [[3, 3, 3]] * 6
    assert len(summary["planner_output"]["planner_conv_kernel_sizes_diagnostic_only_zyx"]) == 6


