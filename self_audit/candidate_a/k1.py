"""K1 query selection and the Candidate-A student loss.

The implementation is intentionally tied to the concrete Candidate-A
contracts in :mod:`bank`, :mod:`codec`, and :mod:`model`:

* ``QueryBank`` IDs are stable integer indices and ``QueryBank.targets`` is
  the only source of labelled query targets.
* ``MeasurementCodec`` performs all quantisation and all bit accounting.  No
  guessed float cost or fallback bit width is used.
* ``CandidateAStudent`` exposes ``encode``, ``predict_values``,
  ``policy_logits`` and ``decode``.  The decoder receives only IDs, values,
  and declared geometry.

K1 trials are privileged training operations.  Teacher values can rank
candidate proposals, but a trial always inserts the quantised student value.
The selected prefix is generated by the student's own policy, so utility
targets are recomputed on the actual visited states rather than on an oracle
trajectory.  At inference ``labels`` and ``teacher_values`` are omitted and
the exact same policy/STOP/budget path is used without a teacher.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
from typing import Any, Mapping, Optional, Sequence

import torch
from torch import Tensor
from torch.nn import functional as F

from ..losses import supervised_loss


STOP_ID = -1


@dataclass(frozen=True)
class K1Config:
    """Finite K1 rollout recipe.

    ``bit_budget`` is the complete serialized packet budget, including the
    fixed R0 packet/header.  ``baseline_ids`` defaults to ``codec.base_ids``. The
    three proposal counts bound the candidate set; STOP always occupies one
    slot and is valid at step zero.
    """

    max_steps: int = 8
    candidate_limit: int = 8
    teacher_topk: int = 2
    student_topk: int = 2
    random_candidates: int = 2
    temperature: float = 1.0
    cost_lambda: float = 0.0
    bit_budget: int = 1024
    baseline_ids: tuple[int, ...] = ()
    seed: int = 0
    policy_mode: str = "learned"  # learned, random, fixed
    sample_policy: bool = False
    policy_enabled: bool = True
    teacher_proposal_types: tuple[str, ...] = ("REGION", "BOUNDARY")

    def __post_init__(self) -> None:
        if type(self.bit_budget) is not int or self.bit_budget < 0:
            raise ValueError("bit_budget must be a non-negative integer")
        if type(self.max_steps) is not int or self.max_steps < 0:
            raise ValueError("max_steps must be a non-negative integer")
        if type(self.candidate_limit) is not int or self.candidate_limit < 1:
            raise ValueError("candidate_limit must be at least one for STOP")
        counts = (self.teacher_topk, self.student_topk, self.random_candidates)
        if any(type(value) is not int or value < 0 for value in counts):
            raise ValueError("proposal counts must be non-negative")
        if not math.isfinite(self.temperature) or self.temperature <= 0:
            raise ValueError("temperature must be finite and positive")
        if not math.isfinite(self.cost_lambda) or self.cost_lambda < 0:
            raise ValueError("cost_lambda must be finite and non-negative")
        if type(self.sample_policy) is not bool or type(self.policy_enabled) is not bool:
            raise ValueError("sample_policy and policy_enabled must be boolean")
        teacher_proposal_types = tuple(str(kind).upper() for kind in self.teacher_proposal_types)
        if not teacher_proposal_types or len(set(teacher_proposal_types)) != len(teacher_proposal_types) \
                or any(kind not in {"REGION", "BOUNDARY"} for kind in teacher_proposal_types):
            raise ValueError("teacher_proposal_types must be a non-empty subset of REGION and BOUNDARY")
        object.__setattr__(self, "teacher_proposal_types", teacher_proposal_types)
        if len(set(self.baseline_ids)) != len(self.baseline_ids) or any(type(i) is not int or i < 0 for i in self.baseline_ids):
            raise ValueError("baseline_ids must be unique non-negative integer bank IDs")
        if self.policy_mode not in {"learned", "random", "fixed"}:
            raise ValueError("policy_mode must be learned, random, or fixed")


@dataclass
class CandidateTrace:
    step: int
    state_ids: tuple[int, ...]
    state_bits: int
    candidate_ids: tuple[int, ...]
    utilities: Tensor
    target_probs: Optional[Tensor]
    policy_logits: Optional[Tensor]
    selected_id: int
    selected_cost_bits: int


@dataclass
class RolloutResult:
    final_logits: Tensor
    traces: list[CandidateTrace]
    code_ids: tuple[int, ...]
    code_values: Tensor
    code_bits: int
    query_count: int
    query_predictions: Tensor
    segmentation_loss: Optional[Tensor] = None
    region_query_loss: Optional[Tensor] = None
    boundary_query_loss: Optional[Tensor] = None
    policy_loss: Optional[Tensor] = None
    total_loss: Optional[Tensor] = None

    @property
    def code(self) -> dict[str, Any]:
        return {"ids": list(self.code_ids), "values": self.code_values.detach().clone(),
                "query_count": self.query_count, "bits": self.code_bits}


def _kind_tensor(bank: Any, device: torch.device) -> Tensor:
    return torch.tensor([1 if bank.query(i).kind == "BOUNDARY" else 0 for i in range(len(bank))],
                        dtype=torch.long, device=device)


def query_losses(predicted: Tensor, target: Tensor, bank: Any) -> tuple[Tensor, Tensor]:
    predicted = _batch_values(predicted)
    target = _batch_values(target).to(device=predicted.device, dtype=predicted.dtype)
    if predicted.shape != target.shape or predicted.shape[1] != len(bank):
        raise ValueError("query prediction/target tensors must be [B,len(bank)]")
    kinds = _kind_tensor(bank, predicted.device)
    zero = predicted.sum() * 0
    region = (predicted[:, kinds == 0] - target[:, kinds == 0]).abs().mean() if bool((kinds == 0).any()) else zero
    boundary = ((predicted[:, kinds == 1] - target[:, kinds == 1]).abs() / 2).mean() if bool((kinds == 1).any()) else zero
    return region, boundary


def _batch_values(value: Tensor) -> Tensor:
    if not isinstance(value, Tensor):
        value = torch.as_tensor(value)
    if value.ndim == 1:
        value = value.unsqueeze(0)
    if value.ndim != 2:
        raise ValueError("query values must be [Q] or [B,Q]")
    return value


def _geometry_parts(geometry: Any) -> tuple[tuple[int, ...], tuple[float, ...]]:
    """Normalize 2-D or 3-D public geometry for K1 and packet accounting."""

    if not isinstance(geometry, Mapping) or "shape" not in geometry:
        raise ValueError("geometry must declare shape and a matching spacing tuple")
    shape_raw = geometry["shape"]
    if "spacing_yx" in geometry and "spacing_zyx" not in geometry:
        spacing_raw = geometry["spacing_yx"]
    elif "spacing_zyx" in geometry and "spacing_yx" not in geometry:
        spacing_raw = geometry["spacing_zyx"]
    else:
        raise ValueError("geometry must declare exactly one of spacing_yx or spacing_zyx")
    if not isinstance(shape_raw, (tuple, list)) or not isinstance(spacing_raw, (tuple, list)):
        raise ValueError("geometry shape and spacing must be tuples/lists")
    if len(shape_raw) not in (2, 3):
        raise ValueError("geometry must declare a 2-D or 3-D shape")
    expected_spacing_key = "spacing_yx" if len(shape_raw) == 2 else "spacing_zyx"
    actual_spacing_key = "spacing_yx" if "spacing_yx" in geometry else "spacing_zyx"
    if actual_spacing_key != expected_spacing_key or len(spacing_raw) != len(shape_raw):
        raise ValueError("2-D geometry requires spacing_yx; 3-D geometry requires spacing_zyx")
    if any(type(v) is not int or v <= 0 for v in shape_raw):
        raise ValueError("geometry shape must contain positive integers")
    shape = tuple(shape_raw)
    try:
        spacing = tuple(float(value) for value in spacing_raw)
    except (TypeError, ValueError) as exc:
        raise ValueError("geometry spacing must contain finite numbers") from exc
    if min(shape) <= 0 or not all(math.isfinite(v) and v > 0 for v in spacing):
        raise ValueError("geometry shape/spacing must be positive and finite")
    if len(shape) == 3:
        required_3d = {"affine_zyx", "context"}
        if not required_3d.issubset(geometry) or geometry["context"] != "full_volume":
            raise ValueError("3-D geometry must declare affine_zyx and context='full_volume'")
    return shape, spacing


def _codec_geometry_kwargs(geometry: Any, shape: tuple[int, ...], spacing: tuple[float, ...]) -> dict[str, Any]:
    """Map shared K1 geometry to the concrete codec packet contract."""
    kwargs: dict[str, Any] = {"shape": shape, "spacing": spacing}
    if len(shape) == 3:
        if "affine_zyx" not in geometry:
            raise ValueError("3-D packet accounting requires affine_zyx")
        kwargs["affine_zyx"] = geometry["affine_zyx"]
    return kwargs


def _base_ids(codec: Any, config: K1Config) -> tuple[int, ...]:
    ids = config.baseline_ids or tuple(codec.base_ids)
    if len(set(ids)) != len(ids) or any(i < 0 or i >= len(codec.bank) for i in ids):
        raise ValueError("R0 IDs must be unique IDs in the measurement bank")
    if tuple(codec.base_ids) and tuple(ids) != tuple(codec.base_ids):
        raise ValueError("K1 R0 must equal codec.base_ids")
    return tuple(ids)


def _quantize(codec: Any, values: Tensor, ids: Sequence[int], *, ste: bool) -> Tensor:
    values = _batch_values(values)
    if values.shape[1] != len(ids):
        raise ValueError("value and ID lengths do not match")
    if not ids:
        return values[:, :0]
    return codec.quantize_values(values, tuple(int(i) for i in ids), ste=ste).values


def _single_quantized(codec: Any, full_values: Tensor, query_id: int, *, ste: bool) -> Tensor:
    return _quantize(codec, full_values[:, query_id : query_id + 1], (query_id,), ste=ste)[:, 0]


def _code_bits(codec: Any, ids: Sequence[int], geometry: Any) -> int:
    shape, spacing = _geometry_parts(geometry)
    # MeasurementCodec.cost is the sole authority for header, fingerprint,
    # IDs, value bits and byte padding.  Value contents do not alter packet
    # length.
    return int(codec.cost(tuple(ids), **_codec_geometry_kwargs(geometry, shape, spacing)))


def _incremental_bits(codec: Any, existing: Sequence[int], query_id: int, geometry: Any) -> int:
    shape, spacing = _geometry_parts(geometry)
    return int(codec.incremental_cost(tuple(existing), int(query_id), **_codec_geometry_kwargs(geometry, shape, spacing)))


def _query_values_for_ids(values: Tensor, ids: Sequence[int], query_ids: Sequence[int]) -> Tensor:
    positions = {int(query_id): index for index, query_id in enumerate(ids)}
    try:
        return torch.stack([values[:, positions[int(query_id)]] for query_id in query_ids], dim=1)
    except KeyError as exc:
        raise ValueError(f"query ID {exc.args[0]} missing from value tensor") from exc


def _policy_row(logits: Tensor, candidate_ids: Sequence[int], bank_size: int) -> Tensor:
    """Map model [1,Q+1] policy output to a candidate-restricted row."""

    if logits.ndim != 2 or logits.shape[0] != 1:
        raise ValueError("K1 reference rollout expects policy logits [1,Q+1]")
    row = logits[0]
    if row.numel() != bank_size + 1:
        raise ValueError("CandidateAStudent policy must return Q+1 logits")
    if torch.isnan(row).any() or torch.isposinf(row).any():
        raise FloatingPointError("policy logits contain NaN or +Inf")
    selected = torch.stack([row[bank_size] if query_id == STOP_ID else row[int(query_id)] for query_id in candidate_ids])
    if torch.isnan(selected).any() or torch.isposinf(selected).any():
        raise FloatingPointError("candidate policy logits contain NaN or +Inf")
    return selected


def _feasible_ids(
    bank: Any,
    codec: Any,
    geometry: Any,
    *,
    used: Sequence[int],
    current_bits: int,
    bit_budget: int,
) -> list[int]:
    """Return every bank query that fits the exact serialized budget."""

    used_set = set(int(i) for i in used)
    feasible: list[int] = []
    for query_id in range(len(bank)):
        if query_id in used_set:
            continue
        extra = _incremental_bits(codec, used, query_id, geometry)
        if current_bits + extra <= bit_budget:
            feasible.append(query_id)
    return feasible


def _candidate_ids(
    bank: Any,
    codec: Any,
    geometry: Any,
    *,
    used: Sequence[int],
    current_bits: int,
    config: K1Config,
    student_values: Tensor,
    teacher_values: Optional[Tensor],
    policy_logits: Tensor,
    generator: torch.Generator,
) -> tuple[int, ...]:
    """Generate teacher/student/random proposals after feasibility masking."""

    if config.candidate_limit < 1:
        raise ValueError("candidate_limit must be at least one")
    feasible = _feasible_ids(
        bank, codec, geometry, used=used, current_bits=current_bits,
        bit_budget=config.bit_budget,
    )
    if not feasible:
        return (STOP_ID,)
    feasible_set = set(feasible)
    max_queries = config.candidate_limit - 1
    chosen: list[int] = []

    if not torch.isfinite(student_values).all():
        raise FloatingPointError("student proposal values contain NaN or Inf")

    def add(query_id: int) -> None:
        if query_id in feasible_set and query_id not in chosen and len(chosen) < max_queries:
            chosen.append(query_id)

    # Build bounded proposal streams first.  The streams are interleaved below
    # so a large teacher list cannot consume the complete candidate budget
    # before student and random exploration get a chance to contribute.
    streams: list[list[int]] = []
    stream_limits: list[int] = []

    # Teacher values are proposal-only.  Normalize discrepancies by the query
    # type before sorting, as REGION and signed-distance scales differ.  Each
    # enabled measurement type gets its own top-k stream.
    if teacher_values is not None and config.teacher_topk:
        teacher_values = _batch_values(teacher_values).detach()
        if teacher_values.shape != student_values.shape:
            raise ValueError("teacher query values must be [B,len(bank)]")
        if not torch.isfinite(teacher_values).all() or not torch.isfinite(student_values).all():
            raise FloatingPointError("teacher/student proposal values contain NaN or Inf")
        kind = _kind_tensor(bank, student_values.device)
        scale = torch.where(kind == 1, torch.full_like(kind, 2.0), torch.ones_like(kind))
        discrepancy = (teacher_values - student_values.detach()).abs().mean(0) / scale
        for measurement_type in config.teacher_proposal_types:
            ranked = sorted(
                (i for i in feasible if bank.query(i).kind == measurement_type),
                key=lambda i: (-float(discrepancy[i]), i),
            )
            streams.append(ranked)
            stream_limits.append(config.teacher_topk)

    if config.student_topk:
        if policy_logits.ndim != 2 or policy_logits.shape != (1, len(bank) + 1):
            raise ValueError("student policy logits must have shape [1,Q+1]")
        if torch.isnan(policy_logits).any() or torch.isposinf(policy_logits).any():
            raise FloatingPointError("student policy logits contain NaN or +Inf")
        row = policy_logits[0]
        ranked = sorted(feasible, key=lambda i: (-float(row[i].detach()), i))
        streams.append(ranked)
        stream_limits.append(config.student_topk)

    if config.random_candidates:
        order = torch.randperm(len(feasible), generator=generator).tolist()
        # Keep the complete permutation so duplicates already selected by
        # another source can be skipped without losing the random quota.
        streams.append([feasible[position] for position in order])
        stream_limits.append(config.random_candidates)

    # Round-robin source streams.  A stream advances past duplicates without
    # spending its quota, ensuring random exploration remains distinct whenever
    # an unused feasible query exists.
    positions = [0] * len(streams)
    counts = [0] * len(streams)
    while len(chosen) < max_queries:
        made_progress = False
        for stream_index, stream in enumerate(streams):
            if counts[stream_index] >= stream_limits[stream_index]:
                continue
            while positions[stream_index] < len(stream):
                query_id = stream[positions[stream_index]]
                positions[stream_index] += 1
                if query_id not in feasible_set or query_id in chosen:
                    continue
                chosen.append(query_id)
                counts[stream_index] += 1
                made_progress = True
                break
            if len(chosen) == max_queries:
                break
        if not made_progress:
            break

    # Fill a partially occupied budget deterministically from the remaining
    # feasible bank.  This does not affect source quotas above.
    for query_id in feasible:
        add(query_id)
        if len(chosen) == max_queries:
            break
    return tuple(chosen + [STOP_ID])


def trial_utilities(
    model: Any,
    *,
    current_ids: Sequence[int],
    current_values: Tensor,
    candidate_ids: Sequence[int],
    student_values: Tensor,
    labels: Tensor,
    codec: Any,
    geometry: Any,
    lambda_cost: float = 0.0,
    chunk_size: Optional[int] = None,
) -> Tensor:
    """Compute detached utility using exactly the same decoder/state."""

    if STOP_ID not in candidate_ids:
        raise ValueError("candidate set must contain STOP")
    current_values = _batch_values(current_values)
    student_values = _batch_values(student_values)
    if current_values.shape[0] != labels.shape[0] or student_values.shape[0] != labels.shape[0]:
        raise ValueError("batch mismatch in utility trial")
    if not torch.isfinite(current_values).all() or not torch.isfinite(student_values).all():
        raise FloatingPointError("utility inputs contain NaN or Inf")
    utilities: list[Tensor] = []
    with torch.no_grad():
        base = model.decode(tuple(current_ids), current_values.detach(), geometry, chunk_size=chunk_size)
        base_loss = supervised_loss(base, labels)
        for query_id in candidate_ids:
            if query_id == STOP_ID:
                utilities.append(base_loss.detach() * 0)
                continue
            value = _single_quantized(codec, student_values, int(query_id), ste=False)
            trial_values = torch.cat((current_values.detach(), value[:, None]), dim=1)
            trial = model.decode(tuple(current_ids) + (int(query_id),), trial_values, geometry, chunk_size=chunk_size)
            trial_loss = supervised_loss(trial, labels)
            cost = _incremental_bits(codec, current_ids, int(query_id), geometry)
            utilities.append((base_loss - trial_loss - lambda_cost * cost).detach())
    result = torch.stack(utilities).detach()
    if not torch.isfinite(result).all():
        raise FloatingPointError("utility contains NaN or Inf")
    return result


def policy_cross_entropy(policy_logits: Tensor, candidate_ids: Sequence[int], utilities: Tensor,
                         *, bank_size: int, temperature: float) -> tuple[Tensor, Tensor]:
    """CE on candidate-restricted logits and detached softmax utility target."""

    if not math.isfinite(float(temperature)) or temperature <= 0:
        raise ValueError("temperature must be positive")
    if torch.isnan(policy_logits).any() or not torch.isfinite(utilities).all():
        raise FloatingPointError("policy target/logits contain NaN or Inf")
    restricted = _policy_row(policy_logits, candidate_ids, bank_size)
    target = F.softmax(utilities.detach() / temperature, dim=0).detach()
    loss = -(target * F.log_softmax(restricted, dim=0)).sum()
    if not torch.isfinite(loss):
        raise FloatingPointError("candidate policy loss is non-finite")
    return loss, target


def _teacher_values(teacher: Any, images: Tensor, bank: Any, geometry: Any) -> Tensor:
    """Optional teacher adapter; its forward is always isolated from student.

    The concrete teacher contract exposes ``region_logits`` and normalized
    ``sdf``.  Region probabilities are formed here once under ``no_grad``;
    callers that already made a fixed teacher snapshot should pass
    ``teacher_values`` directly instead.
    """

    if teacher is None:
        raise ValueError("teacher is None")
    with torch.no_grad():
        if callable(teacher):
            # Native-volume teachers require the explicit public geometry for
            # anisotropic SDF conditioning; the established 2-D adapter keeps
            # its image-only call contract.
            output = teacher(images, geometry=geometry) if images.ndim == 5 else teacher(images)
        else:
            output = teacher
        if not isinstance(output, Mapping) or "region_logits" not in output or "sdf" not in output:
            raise ValueError("teacher output must contain region_logits and sdf")
        region_probs = output["region_logits"].softmax(1)
        return bank.teacher_values(region_probs, output["sdf"]).detach()


def student_rollout(
    model: Any,
    images: Tensor,
    bank: Any,
    *,
    codec: Any,
    geometry: Any,
    labels: Optional[Tensor] = None,
    teacher_values: Optional[Tensor] = None,
    teacher: Any = None,
    query_targets: Optional[Tensor] = None,
    config: Optional[K1Config] = None,
    generator: Optional[torch.Generator] = None,
    chunk_size: Optional[int] = None,
) -> RolloutResult:
    """Roll out the student, optionally computing the complete student loss."""

    if images.ndim not in (4, 5) or images.shape[0] != 1:
        raise ValueError("reference rollout requires B=1 image tensors with 2-D or 3-D spatial axes")
    if labels is not None and (labels.ndim != images.ndim - 1 or labels.shape[0] != 1):
        raise ValueError("labels must have B=1 and the image's spatial axes")
    if labels is None and query_targets is not None:
        raise ValueError("query_targets are training-only and require labels")
    config = config or K1Config()
    if config.bit_budget < 0:
        raise ValueError("bit_budget must be non-negative")
    shape, spacing = _geometry_parts(geometry)
    if tuple(images.shape[2:]) != shape:
        raise ValueError("geometry shape does not match image spatial dimensions")
    if labels is not None and tuple(labels.shape[1:]) != shape:
        raise ValueError("geometry shape does not match label spatial dimensions")
    if teacher is not None and teacher_values is not None:
        raise ValueError("pass teacher or teacher_values, not both")
    if teacher is not None:
        teacher_values = _teacher_values(teacher, images, bank, geometry)
    if teacher_values is not None:
        teacher_values = _batch_values(teacher_values).detach()
        if teacher_values.shape != (1, len(bank)):
            raise ValueError("teacher_values must have one value per bank query")
        if not torch.isfinite(teacher_values).all():
            raise FloatingPointError("teacher_values contain NaN or Inf")

    features = model.encode(images)
    # Keep raw student values for Lq and proposal ranking.  Quantisation is
    # applied only when a value is written to a code/trial.
    student_values = model.predict_values(features, geometry=geometry)
    if student_values.shape[1] != len(bank):
        raise ValueError("student value head must output one value per bank query")
    if not torch.isfinite(student_values).all():
        raise FloatingPointError("student query values contain NaN or Inf")
    if labels is not None:
        if query_targets is None:
            query_targets = bank.targets(labels, _geometry_parts(geometry)[1])
        query_targets = _batch_values(query_targets).to(device=student_values.device, dtype=student_values.dtype)
        if query_targets.shape != student_values.shape:
            raise ValueError("query_targets must align with student values")
        if not torch.isfinite(query_targets).all():
            raise FloatingPointError("query_targets contain NaN or Inf")

    base_ids = _base_ids(codec, config)
    if base_ids:
        code_values = _quantize(codec, _query_values_for_ids(student_values, range(len(bank)), base_ids), base_ids, ste=labels is not None)
    else:
        code_values = student_values[:, :0]
    code_ids = list(base_ids)
    current_bits = _code_bits(codec, code_ids, geometry)
    if current_bits > config.bit_budget:
        raise ValueError("fixed R0 code exceeds budget_bits")
    rng = generator or torch.Generator(device="cpu").manual_seed(config.seed)
    traces: list[CandidateTrace] = []
    policy_terms: list[Tensor] = []

    for step in range(config.max_steps):
        remaining = config.bit_budget - current_bits
        policy_all = model.policy_logits(features, tuple(code_ids), code_values, remaining_bits=remaining)
        feasible_ids = _feasible_ids(
            bank, codec, geometry, used=code_ids, current_bits=current_bits,
            bit_budget=config.bit_budget,
        )
        action_ids = tuple(feasible_ids + [STOP_ID])
        candidate_ids = _candidate_ids(
            bank, codec, geometry, used=code_ids, current_bits=current_bits,
            config=config, student_values=student_values.detach(), teacher_values=teacher_values,
            policy_logits=policy_all.detach(), generator=rng,
        )
        restricted = _policy_row(policy_all, candidate_ids, len(bank))
        action_logits = _policy_row(policy_all, action_ids, len(bank))
        if not torch.isfinite(action_logits).all():
            raise FloatingPointError("full feasible policy contains a non-finite action logit")
        utilities = torch.zeros(len(candidate_ids), device=student_values.device, dtype=student_values.dtype)
        target = None
        make_trials = labels is not None and not (
            config.policy_mode in {"fixed", "random"} and not config.policy_enabled
        )
        if make_trials:
            utilities = trial_utilities(
                model, current_ids=tuple(code_ids), current_values=code_values.detach(),
                candidate_ids=candidate_ids, student_values=student_values.detach(), labels=labels,
                codec=codec, geometry=geometry, lambda_cost=config.cost_lambda,
                chunk_size=chunk_size,
            ).to(device=student_values.device, dtype=student_values.dtype)
            if config.policy_enabled and config.policy_mode == "learned":
                loss, target = policy_cross_entropy(policy_all, candidate_ids, utilities,
                                                    bank_size=len(bank), temperature=config.temperature)
                policy_terms.append(loss)

        if config.policy_mode == "random":
            # Random control samples the same full feasible action space as
            # the learned policy, including STOP; it never samples only the
            # teacher's bounded trial proposals.
            selected_index = int(torch.randint(len(action_ids), (1,), generator=rng).item())
            selected_id = int(action_ids[selected_index])
        elif config.policy_mode == "fixed":
            # Fixed control is a deterministic bank order, independent of
            # teacher discrepancy and candidate proposal ordering.
            selected_id = int(feasible_ids[0]) if feasible_ids else STOP_ID
        elif config.sample_policy and labels is not None:
            # torch.Generator is deliberately CPU-owned for reproducibility;
            # sample the detached probability vector on CPU even when the
            # student tensors are on CUDA.
            probs = F.softmax(action_logits.detach().cpu(), dim=0)
            if not torch.isfinite(probs).all():
                raise FloatingPointError("full-policy sampling probabilities are non-finite")
            selected_index = int(torch.multinomial(probs, 1, generator=rng).item())
            selected_id = int(action_ids[selected_index])
        else:
            # Deployment and the ordinary hard rollout use the full feasible
            # bank, not the bounded utility-trial subset.
            selected_id = int(action_ids[int(action_logits.detach().argmax().item())])
        selected_cost = 0
        if selected_id != STOP_ID:
            selected_cost = _incremental_bits(codec, code_ids, selected_id, geometry)
            if current_bits + selected_cost > config.bit_budget:
                raise RuntimeError("selected query exceeded the pre-masked bit budget")
        traces.append(CandidateTrace(
            step=step, state_ids=tuple(code_ids), state_bits=current_bits,
            candidate_ids=tuple(candidate_ids), utilities=utilities.detach(),
            target_probs=None if target is None else target.detach(), policy_logits=restricted,
            selected_id=selected_id, selected_cost_bits=selected_cost,
        ))
        if selected_id == STOP_ID:
            break
        value = _single_quantized(codec, student_values, selected_id, ste=labels is not None)
        code_ids.append(selected_id)
        code_values = torch.cat((code_values, value[:, None]), dim=1)
        current_bits += selected_cost

    final_logits = model.decode(tuple(code_ids), code_values, geometry, chunk_size=chunk_size)
    if not torch.isfinite(final_logits).all():
        raise FloatingPointError("student decoder returned NaN or Inf")
    seg = supervised_loss(final_logits, labels) if labels is not None else None
    region = boundary = None
    if query_targets is not None:
        region, boundary = query_losses(student_values, query_targets, bank)
    policy = torch.stack(policy_terms).mean() if policy_terms else (student_values.sum() * 0 if labels is not None else None)
    total = None
    if labels is not None:
        total = seg + (region if region is not None else student_values.sum() * 0) \
            + (boundary if boundary is not None else student_values.sum() * 0) \
            + (policy if policy is not None else student_values.sum() * 0)
    return RolloutResult(
        final_logits=final_logits, traces=traces, code_ids=tuple(code_ids),
        code_values=code_values, code_bits=current_bits, query_count=len(code_ids),
        query_predictions=student_values, segmentation_loss=seg,
        region_query_loss=region, boundary_query_loss=boundary,
        policy_loss=policy, total_loss=total,
    )


def infer_student(*args: Any, **kwargs: Any) -> RolloutResult:
    kwargs = dict(kwargs)
    for forbidden in ("labels", "teacher", "teacher_values", "query_targets"):
        value = kwargs.pop(forbidden, None)
        if value is not None:
            raise ValueError(f"infer_student does not accept training-only argument {forbidden}")
    return student_rollout(*args, **kwargs)


